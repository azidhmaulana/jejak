import { test, expect } from './fixtures';

test('drawings use rotating colours and survive reload in local storage without server sync', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('bms-language', 'en'));
  await page.route('**/api/auth/session', r => r.fulfill({ json: { setupRequired: false, user: { id: 'drawing-local-test', name: 'Editor', email: 'editor@example.test', role: 'admin', active: true, permissions: ['objects.write'] } } }));
  await page.route('**/api/auth/preferences', r => r.fulfill({ json: { favorites: [], recent: [] } }));
  await page.route('**/api/analytics/events', r => r.fulfill({ json: { ok: true } }));
  const sync: string[] = [];
  page.on('request', req => { if (req.url().includes('/api/bms/projects/')) sync.push(req.url()); });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.locator('.tactical-nav-right button').first().click();
  const panel = page.locator('.objects-panel');
  const point = panel.getByRole('button', { name: 'Point', exact: true });
  await expect(point).toBeEnabled();
  for (const x of [600, 700]) {
    await point.click();
    await page.mouse.click(x, 430);
    await expect(panel.locator('.drawing-object-row')).toHaveCount(x === 600 ? 1 : 2);
  }
  const colours = await panel.locator('.drawing-object-row').evaluateAll(nodes => nodes.map(n => (n as HTMLElement).style.borderLeftColor));
  expect(new Set(colours).size).toBe(2);
  await expect.poll(() => page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('jejak-drawing:')).length)).toBeGreaterThan(0);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.tactical-nav-right button').first().click();
  await expect(panel.locator('.drawing-object-row')).toHaveCount(2);
  await panel.locator('.drawing-object-name').first().click();
  await panel.getByRole('textbox', { name: 'Object name' }).fill('My marker');
  await panel.getByRole('textbox', { name: 'Object name' }).press('Enter');
  await expect(panel.locator('.drawing-object-name').first()).toHaveText('My marker');
  await panel.getByRole('button', { name: 'Edit marker My marker', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Edit marker' })).toBeVisible();
  await page.getByRole('button', { name: 'Close marker editor' }).click();
  await panel.getByRole('button', { name: 'Area', exact: true }).click();
  await page.mouse.click(450, 350);
  const activity = page.getByRole('region', { name: 'Drawing activity' });
  await expect(activity).toContainText('1 points');
  await activity.getByLabel('Border style', { exact: true }).selectOption('dotted');
  await activity.getByLabel('Opacity percent', { exact: true }).fill('0');
  await expect(activity.getByLabel('Object opacity', { exact: true })).toHaveValue('0');
  await page.mouse.move(462, 350);
  await page.screenshot({ path: '.runtime/drawing-near-first-point.png', clip: { x: 435, y: 335, width: 55, height: 35 } });
  await page.mouse.click(650, 350);
  await page.mouse.click(550, 500);
  await expect(activity.getByRole('button', { name: 'Finish', exact: true })).toBeEnabled();
  await activity.getByRole('button', { name: 'Undo point' }).click();
  await expect(activity).toContainText('2 points');
  await page.mouse.click(550, 500);
  await activity.getByRole('button', { name: 'Finish', exact: true }).click();
  await expect(panel.locator('.drawing-object-row')).toHaveCount(3);
  await expect(activity).toHaveCount(0);
  await expect(panel).toHaveAttribute('data-completed', 'true');
  await expect(panel).toHaveAttribute('data-completed', 'false');
  await panel.getByRole('button', { name: 'Close objects', exact: true }).click();
  await expect(panel).toHaveCount(0);
  await page.mouse.click(550, 400);
  await expect(activity).toBeVisible();
  await expect(activity).toContainText('AREA');
  await expect(activity.getByRole('button', { name: 'Done', exact: true })).toBeVisible();
  await expect(activity.getByLabel('Border style', { exact: true })).toHaveValue('dotted');
  await expect(activity.getByLabel('Object opacity', { exact: true })).toHaveValue('0');
  await activity.getByLabel('Object fill', { exact: true }).selectOption('crosshatch');
  await activity.getByLabel('Opacity percent', { exact: true }).fill('45');
  await expect(activity.getByLabel('Object opacity', { exact: true })).toHaveValue('45');
  await activity.locator('.drawing-edit-name').click();
  await activity.getByLabel('Object name', { exact: true }).fill('Area edited');
  await activity.getByLabel('Object name', { exact: true }).press('Enter');
  await expect(activity.locator('.drawing-edit-name')).toHaveText('Area edited');
  await activity.getByRole('button', { name: 'Done', exact: true }).click();
  await expect(activity).toHaveCount(0);
  await page.mouse.click(550, 400);
  await activity.getByRole('button', { name: 'Delete object', exact: true }).click();
  await expect(activity).toHaveCount(0);
  await page.locator('.tactical-nav-right button').first().click();
  await expect(panel.locator('.drawing-object-row')).toHaveCount(2);
  await page.keyboard.press('Control+z');
  await expect(panel.locator('.drawing-object-row')).toHaveCount(3);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.tactical-nav-right button').first().click();
  await expect(panel.locator('.drawing-object-name').filter({ hasText: 'Area edited' })).toBeVisible();
  expect(sync).toHaveLength(0);
  await page.screenshot({ path: '.runtime/drawing-local.png' });
});
