CREATE TABLE IF NOT EXISTS roles (id TEXT PRIMARY KEY, permissions TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  password TEXT NOT NULL, role TEXT NOT NULL REFERENCES roles(id),
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1))
);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT, action TEXT NOT NULL, target TEXT, time BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS routes (id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL, data TEXT NOT NULL, created BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS preferences (user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS camera_sources (name TEXT PRIMARY KEY, active INTEGER NOT NULL CHECK (active IN (0,1)));
CREATE TABLE IF NOT EXISTS analytics_events (
  id TEXT PRIMARY KEY, time BIGINT NOT NULL, kind TEXT NOT NULL,
  visitor TEXT NOT NULL, session TEXT NOT NULL, camera TEXT NOT NULL,
  seconds INTEGER NOT NULL CHECK (seconds BETWEEN 0 AND 30), device TEXT NOT NULL, referrer TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS analytics_migrations (id TEXT PRIMARY KEY);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE INDEX IF NOT EXISTS users_role ON users(role);
CREATE INDEX IF NOT EXISTS routes_user_created ON routes(user_id, created DESC);
CREATE INDEX IF NOT EXISTS audit_time ON audit(time);
CREATE INDEX IF NOT EXISTS analytics_time ON analytics_events(time);
CREATE INDEX IF NOT EXISTS analytics_session ON analytics_events(session,kind,camera,time);
CREATE INDEX IF NOT EXISTS analytics_kind_time ON analytics_events(kind,time);
